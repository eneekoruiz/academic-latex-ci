"""
academic-ci CLI Entrypoint.

Commands:
  academic-ci init      Initialize pre-push hooks and project verification guards.
  academic-ci verify    Run layout 2D collisions, docx reconciliation, and code cleanliness audits.
  academic-ci sync      Synchronize and compile project against Overleaf Cloud.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

from academic_latex_ci.audits.layout import audit_pdf_layout
from academic_latex_ci.audits.reconciliation import audit_reconciliation
from academic_latex_ci.audits.code_lint import audit_code_cleanliness
from academic_latex_ci.core.overleaf import OverleafClient


def cmd_init(args):
    """Sets up pre-push git hooks in the current workspace."""
    root = Path.cwd()
    hooks_dir = root / ".githooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    
    hook_script = hooks_dir / "pre-push"
    hook_content = (
        "#!/bin/sh\n"
        "# Automated Quality Gate Hook generated by academic-latex-ci\n"
        "python -m academic_latex_ci.cli verify\n"
        "if [ $? -ne 0 ]; then\n"
        "  echo '[ABORT] git push rejected by academic-latex-ci quality gate.'\n"
        "  exit 1\n"
        "fi\n"
        "exit 0\n"
    )
    hook_script.write_text(hook_content, encoding="utf-8")
    
    try:
        subprocess.run(["git", "config", "core.hooksPath", ".githooks"], check=True)
        print("[OK] Configured git core.hooksPath -> .githooks")
        print("[OK] Installed pre-push quality gate successfully.")
    except Exception as e:
        print(f"[WARN] Could not configure git hooks automatically: {e}")


def cmd_verify(args):
    """Runs all verification quality gates."""
    root = Path.cwd()
    pdf_path = Path(args.pdf) if args.pdf else (root / "overleaf_downloaded.pdf")
    docx_path = Path(args.docx) if args.docx else None
    tex_dir = Path(args.tex_dir) if args.tex_dir else root

    # Auto-detect docx if not supplied
    if not docx_path:
        found_docx = list(root.glob("*.docx"))
        if found_docx:
            docx_path = found_docx[0]

    all_defects = []

    print("\n============================================================")
    print("🔍 [Quality Gate 1/3] Auditing Code Cleanliness...")
    print("============================================================")
    code_defects = audit_code_cleanliness(root)
    if code_defects:
        all_defects.extend(code_defects)
        for d in code_defects:
            print(f"  ❌ {d}")
    else:
        print("  ✅ [PASS] 0 residual placeholders, fake values, or unfinished TODOs.")

    if docx_path and docx_path.exists():
        print("\n============================================================")
        print(f"🔍 [Quality Gate 2/3] Auditing Reconciliation with '{docx_path.name}'...")
        print("============================================================")
        ok, recon_defects = audit_reconciliation(docx_path, tex_dir)
        if not ok:
            all_defects.extend(recon_defects)
            for d in recon_defects:
                print(f"  ❌ {d}")
        else:
            print("  ✅ [PASS] Document and metadata parity verified.")
    else:
        print("\n[INFO] Skipping reconciliation audit (no .docx reference specified).")

    if pdf_path.exists():
        print("\n============================================================")
        print(f"🔍 [Quality Gate 3/3] Running 2D Layout & Collision Audit on '{pdf_path.name}'...")
        print("============================================================")
        ok, layout_defects = audit_pdf_layout(pdf_path, tex_dir=tex_dir)
        if not ok:
            all_defects.extend(layout_defects)
            for d in layout_defects:
                print(f"  ❌ {d}")
        else:
            print("  ✅ [PASS] All pages passed strict layout & typography audit cleanly (0 defects).")
    else:
        print(f"\n[INFO] PDF '{pdf_path.name}' not found locally. Run 'academic-ci sync' to download and compile.")

    print("\n============================================================")
    if all_defects:
        print(f"❌ [FAIL] Quality gates detected {len(all_defects)} defects.")
        sys.exit(1)
    else:
        print("✅ [PASS] All quality gates cleared with 0 defects.")
        sys.exit(0)


def cmd_sync(args):
    """Compiles on Overleaf and downloads the resulting PDF."""
    root = Path.cwd()
    project_id = args.project_id
    cookie_file = Path(args.cookie_file) if args.cookie_file else (root / ".olauth")
    out_pdf = Path(args.out) if args.out else (root / "overleaf_downloaded.pdf")

    if not project_id:
        print("[ERROR] Please provide --project-id <overleaf_id>")
        sys.exit(1)

    client = OverleafClient(project_id=project_id, cookie_file=cookie_file)
    print(f"-> Compiling project {project_id} on Overleaf Cloud...")
    try:
        downloaded = client.compile_and_download(out_pdf)
        print(f"[OK] Successfully compiled and saved PDF to: {downloaded}")
    except Exception as e:
        print(f"[FAIL] Cloud compilation failed: {e}")
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(
        prog="academic-ci",
        description="Continuous Integration, 2D Collision Detection, and Layout Verification for Academic LaTeX."
    )
    subparsers = parser.add_subparsers(dest="subcommand", required=True)

    # init
    p_init = subparsers.add_parser("init", help="Set up pre-push hooks and workspace guards.")
    p_init.set_defaults(func=cmd_init)

    # verify
    p_verify = subparsers.add_parser("verify", help="Run 2D collision, reconciliation, and code cleanliness audits.")
    p_verify.add_argument("--pdf", type=str, default=None, help="Path to PDF to audit.")
    p_verify.add_argument("--docx", type=str, default=None, help="Path to reference docx.")
    p_verify.add_argument("--tex-dir", type=str, default=None, help="Path to LaTeX sources.")
    p_verify.set_defaults(func=cmd_verify)

    # sync
    p_sync = subparsers.add_parser("sync", help="Compile and sync document with Overleaf Cloud.")
    p_sync.add_argument("--project-id", type=str, required=True, help="Overleaf Project ID.")
    p_sync.add_argument("--cookie-file", type=str, default=".olauth", help="Path to .olauth session cookie.")
    p_sync.add_argument("--out", type=str, default="overleaf_downloaded.pdf", help="Output PDF path.")
    p_sync.set_defaults(func=cmd_sync)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
